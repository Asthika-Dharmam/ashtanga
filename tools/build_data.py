#!/usr/bin/env python3
"""Build this app's data from the Adyatithi panchaanga's published data.

The panchaanga PWA (https://adyatithi.github.io/panchaanga/) publishes everything it shows as
static JSON under data/, generated by the adyatithi-panchaanga exporter from jyotisham/jyotisha and
jyotisham/adyatithi. This app does not read that site at run time: this script copies what it needs,
for its few cities, into data/ here, cut down to the fields it uses, and the app reads only that.

  python3 tools/build_data.py --src ../panchaanga/data

  --src     the data/ folder of a checkout of adyatithi/panchaanga (or of adyatithi-panchaanga/app)
  --cities  Chennai,Kanchipuram,Mumbai,NewDelhi (ids as in the panchaanga's index.json)

Writes:
  data/index.json                the cities, their Kali years, the scripts and the build
  data/c/<city>/<kali>.json      one Kali year of days for a city, the fields the app uses
  data/s/<script>.json           names in one script: the panchaanga's (tithi, nakshatra, ...,
                                 sankalpa), the festivals the days carry, and the Ashtanga tables
                                 (tools/ashtanga_hk.json) transliterated

Needs indic_transliteration (pip install indic_transliteration).
"""
import argparse
import json
import re
import os
import shutil
import sys

from indic_transliteration import sanscript

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# The festivals the Kanchi Ashtangam prints on its panchanga pages (the repositories that
# kamakoti-panchangam/ashtanga/bin/write_periodical_monthly_panchangam_ashtangam_tex.py reads),
# less those that go on its Ashtanga pages (below).
PANCHANGA_REPOS = {
  'devatA/gaNapati', 'devatA/graha', 'devatA/kaumAra', 'devatA/lakShmI', 'devatA/misc-fauna',
  'devatA/misc-flora', 'devatA/nadI', 'devatA/pitR', 'devatA/shaiva', 'devatA/shakti', 'devatA/umA',
  'devatA/vaiShNava', 'gRhya/Apastamba', 'gRhya/general', 'general', 'mahApuruSha/kAnchI-maTha',
  'mahApuruSha/smArta-misc', 'tamil', 'time_focus/Eclipses', 'time_focus/amrita-siddhi',
  'time_focus/misc', 'time_focus/misc_combinations', 'time_focus/special-tithis',
  'time_focus/tithi-vara-combinations', 'time_focus/monthly/amAvAsyA', 'time_focus/monthly/dvAdashI',
  'time_focus/monthly/ekAdashI', 'time_focus/monthly/pradoSha', 'time_focus/nakShatra',
  'time_focus/puShkara', 'time_focus/sankrAnti', 'time_focus/yugAdiH', 'time_focus/manvAdiH',
}
# The Ashtanga pages: the devI-parvas and pancha-parvas, the dasha-mahAvidyA jayantIs, and the
# four navarAtras (whatever repository holds them).
ASHTANGA_REPOS = {'devatA/devIparva', 'devatA/dashamahAvidyA'}
NAVARATRA = ('vasantanavarAtra', 'vArAhI-navarAtra', 'zarannavarAtra', 'zyAmaLAnavarAtra')
# Observances the exporter makes itself (no repository): of these, the EkAdazIs and amAvAsyAs.
GENERATED = re.compile(r'EkAdazI|amAvAsyA')

# What a day keeps of the panchaanga's day record.
DAY_FIELDS = ('date', 'wd', 'ayana', 'rtu', 'saura', 'chandra', 'sun', 'sun_s', 'moon', 'moon_rise_first',
              'next_sunrise', 'tithi', 'nakshatra', 'yoga', 'karana', 'rashi', 'shula', 'amritadi',
              'raahu', 'yama', 'gulika', 'durmuhurta', 'tyajya', 'amrta')
STATIC_FIELDS = ('script', 'tithi', 'nakshatra', 'yoga', 'karana', 'rashi', 'vara', 'samvatsara', 'ayana',
                 'rtu', 'chandramasa', 'amritadi', 'shula', 'digits', 'sankalpa')
SCRIPTS = {'devanagari': sanscript.DEVANAGARI, 'tamil': sanscript.TAMIL, 'grantha': sanscript.GRANTHA,
           'telugu': sanscript.TELUGU, 'kannada': sanscript.KANNADA, 'iso': sanscript.ISO}


def load(path):
  with open(path, encoding='utf-8') as f:
    return json.load(f)


def dump(obj, path, pretty=False):
  os.makedirs(os.path.dirname(path), exist_ok=True)
  with open(path, 'w', encoding='utf-8') as f:
    if pretty:
      json.dump(obj, f, ensure_ascii=False, indent=1)
    else:
      json.dump(obj, f, ensure_ascii=False, separators=(',', ':'))
    f.write('\n')


def tr(text, script, names=False):
  # In a name, OM is the vowel O with an anusvAra (ओं, as the Ashtangam prints it), not the praNava.
  if names:
    text = text.replace('OM', 'O\u200cM')
  out = sanscript.transliterate(text, sanscript.roman.HK_DRAVIDIAN, SCRIPTS[script]).replace('\u200c', '')
  if script == 'tamil':
    out = sanscript.SCHEMES[sanscript.TAMIL].apply_roman_numerals(out)
  return out


def fest_key(entry):
  return entry.get('k', entry['id'])


def is_ashtanga(key, repo):
  return repo in ASHTANGA_REPOS or key.startswith(NAVARATRA)


def build_days(src, city, year, fest_repo, used):
  meta = load(os.path.join(src, 'c', city, str(year['kali']), 'meta.json'))
  days = []
  for ym in meta['months']:
    for d in load(os.path.join(src, 'c', city, str(year['kali']), ym + '.json')):
      if not (year['start'] <= d['date'] <= year['end']):
        continue
      out = {k: d[k] for k in DAY_FIELDS if k in d}
      # The abhijit muhUrta: the eighth of the fifteen day muhUrtas (the list holds their ends).
      mu = d.get('muhurta')
      if mu and len(mu[0]) >= 8:
        out['abhijit'] = [mu[0][6], mu[0][7]]
      p, a = [], []
      for e in d.get('fest', []):
        key = fest_key(e)
        repo = fest_repo.get(key) or fest_repo.get(e['id'], '')
        if is_ashtanga(key, repo):
          a.append(key)
        elif repo in PANCHANGA_REPOS or (not repo and GENERATED.search(key)):
          p.append(key)
        else:
          continue
        used.add(key)
      if p:
        out['fp'] = p
      if a:
        out['fa'] = a
      days.append(out)
  return {'schema': 1, 'city': city, 'kali': year['kali'], 'samvatsara': meta['samvatsara'],
          'start': year['start'], 'end': year['end'], 'days': days}


def build_script(src, script, used, hk):
  static = load(os.path.join(src, 'static', script + '.json'))
  names = load(os.path.join(src, 'text', script, 'fest.json'))
  out = {k: static[k] for k in STATIC_FIELDS if k in static}
  out['fest'] = {k: names.get(k, k) for k in sorted(used)}
  # The kAlas of the pUjA times on parva days.
  out['kaala'] = {k: static['kaala'][k] for k in ('pradosha', 'madhyaraatri', 'aparaahna') if k in static.get('kaala', {})}
  T = lambda s: tr(s, script)
  N = lambda s: tr(s, script, names=True)
  a = {k: [N(x) for x in hk[k]] for k in ('tattva', 'rtu', 'nityamasa', 'kalamasa', 'nitya30',
                                          'kalanitya', 'vasara', 'ghatika', 'nakshatra', 'yoga', 'karana')}
  a['visesha'] = {k: [N(v[0]), N(v[1])] for k, v in hk['visesha'].items()}
  a['phrases'] = {k: T(v) for k, v in hk['phrases'].items()}
  a['labels'] = {k: T(v) for k, v in hk['labels'].items()}
  # The dinanityAvidyA, as the generators put it together: the tattvavatsara's letter with the
  # nityAmAsa's vowel, then the tattvadivasa's letter with A, then 'I haMsaH'. Joined here (the
  # PDF prints it joined), so it is kept as its two variable parts, pre-transliterated.
  stem = lambda s: s.split()[0]
  # citrA and mahAnityA (the 15th and 16th nityAmAsas) are a bare M and H in the generators'
  # tables, apart from kAmEzvarI's aM; they give aM and aH here, where kAmEzvarI's gives a.
  def akshara(name, bare=False):
    x = stem(name)
    if bare:
      return x
    x = x.rstrip('M')
    if x != 'a' and x.endswith('a'):
      x = x[:-1]
    return x
  a['vidya1'] = [[T((akshara(v) + akshara(n)).replace('aa', 'a').replace('aA', 'A')) for n in hk['nityamasa'][:14]] + [T((akshara(v) + x).replace('aa', 'a')) for x in ('aM', 'aH')]
                 for v in hk['tattva']]
  a['vidya2'] = [T((akshara(d) + 'A').replace('aA', 'A')) for d in hk['tattva']]
  a['vidya3'] = T('IhaMsaH')
  out['ashtanga'] = a
  return out


def main():
  ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument('--src', default=os.path.join(ROOT, '..', 'panchaanga', 'data'))
  ap.add_argument('--cities', default='Chennai,Kanchipuram,Mumbai,NewDelhi')
  ap.add_argument('--out', default=os.path.join(ROOT, 'data'))
  args = ap.parse_args()
  src, out = args.src, args.out
  index = load(os.path.join(src, 'index.json'))
  if index.get('schema') != 1:
    sys.exit(f'Unknown panchaanga data schema {index.get("schema")}')
  fest_repo = load(os.path.join(src, 'repos.json'))['fest']
  hk = load(os.path.join(HERE, 'ashtanga_hk.json'))
  wanted = args.cities.split(',')
  cities = [c for c in index['cities'] if c['id'] in wanted]
  missing = set(wanted) - {c['id'] for c in cities}
  if missing:
    sys.exit(f'Not in the panchaanga data: {", ".join(sorted(missing))}')

  for sub in ('c', 's'):
    shutil.rmtree(os.path.join(out, sub), ignore_errors=True)
  used = set()
  for c in cities:
    for y in c['years']:
      dump(build_days(src, c['id'], y, fest_repo, used), os.path.join(out, 'c', c['id'], f'{y["kali"]}.json'))
  for script in index['scripts']:
    dump(build_script(src, script, used, hk), os.path.join(out, 's', script + '.json'))
  # Cities in the order asked for.
  cities.sort(key=lambda c: wanted.index(c['id']))
  dump({'schema': 1, 'scripts': index['scripts'],
        'cities': [{k: c[k] for k in ('id', 'label', 'name', 'lat', 'lon', 'tz', 'years')} for c in cities],
        'build': index['build']}, os.path.join(out, 'index.json'), pretty=True)
  print(f'{len(cities)} cities, {len(index["scripts"])} scripts, {len(used)} festivals -> {out}')


if __name__ == '__main__':
  main()
